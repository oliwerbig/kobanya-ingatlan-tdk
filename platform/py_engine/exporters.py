_LATEX_ESCAPE_MAP = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}
_LATEX_ESCAPE_RE = re.compile("|".join(re.escape(k) for k in _LATEX_ESCAPE_MAP))


def _latex_escape(text: str) -> str:
    """Normalize newlines/unicode dashes and escape LaTeX special characters cleanly in a single pass."""
    s = str(text).replace("\r\n", " ").replace("\n", " ").replace("\r", " ")
    s = _LATEX_ESCAPE_RE.sub(lambda m: _LATEX_ESCAPE_MAP[m.group(0)], s)
    s = s.replace("<=", r"$\le$").replace(">=", r"$\ge$")
    s = s.replace("\u2014", "---").replace("\u2013", "--")
    return s


def _sig_stars(p: Optional[float]) -> str:
    if p is None:
        return ""
    if p < 0.01:
        return "$^{***}$"
    if p < 0.05:
        return "$^{**}$"
    if p < 0.10:
        return "$^{*}$"
    return ""


def generate_multi_model_latex(
    ols_models: List[Dict[str, Any]],
    caption: str = "Hedonic & Spatial Regression Comparison",
    label: str = "tab:geospec_models",
    show_pct_for_dummies: bool = False,
    conditional_boxcox: Optional[Dict[str, Any]] = None,
    boxcox_info: Optional[Dict[str, Any]] = None,
) -> str:
    """
    Generate an Overleaf-ready `booktabs` multi-model LaTeX table comparing composed specs.
    Includes standard errors in parentheses, significance stars, diagnostic footer, and Guard footnotes.
    """
    if not ols_models:
        return "% No fitted OLS models available."

    # Collect ordered union of variable names across models
    var_order: List[str] = []
    seen = set()
    for m in ols_models:
        for row in m.get("params", []):
            name = row["name"]
            if name not in seen:
                seen.add(name)
                var_order.append(name)

    safe_label = re.sub(r"[^A-Za-z0-9:._-]", "_", str(label))
    n_cols = len(ols_models)
    col_spec = "l" + "c" * n_cols
    headers = " & ".join(_latex_escape(m.get("model_name", m["model_id"])) for m in ols_models)

    lines = [
        "% Generated by GeoSpec (Pure NumPy+SciPy Spatial Econometric Workbench)",
        "% Requires: \\usepackage{booktabs,threeparttable,amsmath}",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\begin{threeparttable}",
        f"\\caption{{{_latex_escape(caption)}}}",
        f"\\label{{{safe_label}}}",
        f"\\begin{{tabular}}{{{col_spec}}}",
        "\\toprule",
        f"Variable & {headers} \\\\",
        "\\midrule",
    ]

    model_param_maps = [{r["name"]: r for r in m.get("params", [])} for m in ols_models]

    for vname in var_order:
        coef_cells = []
        se_cells = []
        for pmap in model_param_maps:
            if vname in pmap:
                r = pmap[vname]
                stars = _sig_stars(r.get("p"))
                if show_pct_for_dummies and r.get("kennedy_pct") is not None:
                    coef_cells.append(f"{r['beta']:.4f}{stars} [{r['kennedy_pct']:+.1f}\\%]")
                else:
                    coef_cells.append(f"{r['beta']:.4f}{stars}")
                se_cells.append(f"({r['se']:.4f})")
            else:
                coef_cells.append("---")
                se_cells.append("")
        lines.append(f"{_latex_escape(vname)} & " + " & ".join(coef_cells) + " \\\\")
        if any(se_cells):
            lines.append(" & " + " & ".join(se_cells) + " \\\\")

    lines.append("\\midrule")

    def _footer_row(title: str, key: str, fmt: str = "{:.4f}") -> str:
        vals = []
        for m in ols_models:
            v = m.get(key)
            if v is None:
                diag = m.get("diagnostics", {})
                v = diag.get(key)
            if isinstance(v, (int, float)):
                vals.append(fmt.format(v))
            elif v is not None:
                vals.append(_latex_escape(str(v)))
            else:
                vals.append("---")
        return f"{title} & " + " & ".join(vals) + " \\\\"

    lines.append(_footer_row("$N$", "n_obs", "{:d}"))
    lines.append(_footer_row("$R^2$", "r2", "{:.4f}"))
    lines.append(_footer_row("Adj. $R^2$", "adj_r2", "{:.4f}"))
    lines.append(_footer_row("AIC", "aic", "{:.2f}"))
    has_y_scale = any(
        m.get("aic_y_scale") is not None and m.get("aic_y_scale") != m.get("aic")
        for m in ols_models
    )
    if has_y_scale:
        lines.append(_footer_row("AIC ($y$-scale)", "aic_y_scale", "{:.2f}"))
    lines.append(_footer_row("Max VIF", "max_vif", "{:.2f}"))
    lines.append(_footer_row("RESET $p$-value", "reset_p", "{:.4f}"))
    lines.append(_footer_row("SE Type", "cov_type_used", "{}"))
    lines.extend(["\\bottomrule", "\\end{tabular}"])

    # Collect Guard footnotes
    notes: List[str] = ["Standard errors in parentheses. $^{***}p<0.01$, $^{**}p<0.05$, $^{*}p<0.10$. AIC uses the ML $k+1$ parameter count (including $\\sigma^2$)."]
    if len({m.get("n_obs") for m in ols_models if m.get("n_obs") is not None}) > 1:
        notes.append("Note: Models have different sample sizes $N$ (common-sample lock disabled); AIC values are not directly comparable across differing samples.")
    if any(m.get("is_log_scale") for m in ols_models):
        notes.append("Semi-log dummy impacts computed via Halvorsen--Palmquist and Kennedy (1981) variance-corrected transformations.")
    if any(m.get("y_transform") == "boxcox" for m in ols_models):
        lam_txt = (
            f"$\\hat{{\\lambda}} = {boxcox_info['lambda_used']:.4f}$ ({_latex_escape(str(boxcox_info.get('mode', 'mle')))})"
            if isinstance(boxcox_info, dict) and boxcox_info.get("lambda_used") is not None
            else "estimated $\\hat{\\lambda}$"
        )
        notes.append(f"Dependent variable uses Box--Cox transformation with {lam_txt}; coefficients are on the Box--Cox scale.")
    if conditional_boxcox:
        has_log_y = any(m.get("y_transform") in ("log", "log1p") for m in ols_models)
        has_raw_y = any(m.get("y_transform") == "raw" for m in ols_models)
        p_log = conditional_boxcox.get("p_vs_log")
        p_lin = conditional_boxcox.get("p_vs_linear")
        if has_log_y and isinstance(p_log, (int, float)) and float(p_log) < 0.05:
            notes.append(
                f"Conditional Box--Cox MLE check ({_latex_escape(str(conditional_boxcox.get('model_id', 'ref')))}): "
                f"$\\hat{{\\lambda}} = {conditional_boxcox.get('lambda_mle')}$, $p_{{\\text{{vs log}}}} = {p_log}$."
            )
        if has_raw_y and isinstance(p_lin, (int, float)) and float(p_lin) < 0.05:
            notes.append(
                f"Conditional Box--Cox MLE check ({_latex_escape(str(conditional_boxcox.get('model_id', 'ref')))}): "
                f"$\\hat{{\\lambda}} = {conditional_boxcox.get('lambda_mle')}$, $p_{{\\text{{vs linear}}}} = {p_lin}$."
            )
    for m in ols_models:
        mid_esc = _latex_escape(str(m.get("model_id", "")))
        for fn in m.get("footnotes", []):
            notes.append(f"[{mid_esc}] {_latex_escape(fn)}")

    lines.append("\\begin{tablenotes}[flushleft]")
    lines.append("\\small")
    for note in notes:
        lines.append(f"\\item {note}")
    lines.append("\\end{tablenotes}")
    lines.append("\\end{threeparttable}")
    lines.append("\\end{table}")
    return "\n".join(lines)


def _csv_safe_cell(val: Any) -> Any:
    """Neutralize CSV formula injection (OWASP) on string values without altering numeric scalars."""
    if not isinstance(val, str) or not val:
        return val
    stripped = val.lstrip(" \t\r\n")
    if val[0] in ("=", "+", "-", "@", "\t", "\r") or (stripped and stripped[0] in ("=", "+", "-", "@")):
        return "'" + val
    return val


def _union_keys(rows: List[Dict[str, Any]]) -> List[str]:
    ordered: List[str] = []
    seen = set()
    for r in rows:
        for k in r.keys():
            if k not in seen:
                seen.add(k)
                ordered.append(k)
    return ordered


def dict_rows_to_csv(rows: List[Dict[str, Any]]) -> str:
    """Serialize list of dicts (using ordered union of keys) to UTF-8 CSV with formula-injection safety."""
    if not rows:
        return ""
    buf = io.StringIO()
    raw_headers = _union_keys(rows)
    safe_headers = [_csv_safe_cell(str(h)) for h in raw_headers]
    writer = csv.writer(buf)
    writer.writerow(safe_headers)
    for r in rows:
        writer.writerow([_csv_safe_cell(r.get(h)) for h in raw_headers])
    return buf.getvalue()


def _md_escape_cell(val: Any) -> str:
    if val is None:
        return ""
    return str(val).replace("\r\n", " ").replace("\n", " ").replace("\r", " ").replace("|", "\\|")


def dict_rows_to_markdown(rows: List[Dict[str, Any]]) -> str:
    """Serialize list of dicts to GitHub-Flavored Markdown table with pipe & newline escaping."""
    if not rows:
        return ""
    headers = _union_keys(rows)
    lines = [
        "| " + " | ".join(_md_escape_cell(h) for h in headers) + " |",
        "| " + " | ".join(":---" for _ in headers) + " |",
    ]
    for r in rows:
        lines.append("| " + " | ".join(_md_escape_cell(r.get(h)) for h in headers) + " |")
    return "\n".join(lines)


def _clean_opt_float(val: Any) -> Optional[float]:
    if val is None or isinstance(val, bool):
        return None
    try:
        fv = float(val)
        return fv if math.isfinite(fv) else None
    except (TypeError, ValueError):
        return None


def _dedup_safe_names(names: List[str]) -> List[str]:
    seen: Dict[str, int] = {}
    out: List[str] = []
    for raw in names:
        base = "".join(ch if ch.isalnum() else "_" for ch in str(raw)).strip("_") or "col"
        cnt = seen.get(base, 0) + 1
        seen[base] = cnt
        out.append(base if cnt == 1 else f"{base}_{cnt}")
    return out


def build_qgis_geojson(
    lat_arr: List[Optional[float]],
    lon_arr: List[Optional[float]],
    row_ids: List[Any],
    y_raw: List[Optional[float]],
    y_trans: List[Optional[float]],
    dist_dict: Dict[str, Dict[str, Any]],
    active_ols: Optional[Dict[str, Any]] = None,
    spatial_res: Optional[Dict[str, Any]] = None,
    gwr_res: Optional[Dict[str, Any]] = None,
    analytic_indices: Optional[List[int]] = None,
) -> Dict[str, Any]:
    """
    Build RFC-7946 EPSG:4326 GeoJSON FeatureCollection enriched with computed OSM distances,
    travel times, circuity, OLS residuals, LISA clusters, and native GWR/MGWR local parameters.
    """
    analytic_pos_map: Dict[int, int] = {}
    if analytic_indices is not None:
        analytic_pos_map = {int(orig_i): pos for pos, orig_i in enumerate(analytic_indices)}

    def _make_pos_map(stage_dict: Optional[Dict[str, Any]]) -> Dict[int, int]:
        if stage_dict and stage_dict.get("valid_indices") is not None:
            return {int(orig_i): pos for pos, orig_i in enumerate(stage_dict["valid_indices"])}
        return analytic_pos_map

    ols_pos_map = _make_pos_map(active_ols)
    sp_pos_map = _make_pos_map(spatial_res)
    gwr_pos_map = _make_pos_map(gwr_res)

    gwr_safe_cols = (
        _dedup_safe_names(list(gwr_res.get("col_names", [])))
        if gwr_res and gwr_res.get("col_names")
        else []
    )

    features = []
    for idx in range(len(lat_arr)):
        lat_v = lat_arr[idx]
        lon_v = lon_arr[idx]
        if lat_v is None or lon_v is None:
            continue
        props: Dict[str, Any] = {
            "row_id": row_ids[idx] if idx < len(row_ids) else idx,
            "y_raw": y_raw[idx] if idx < len(y_raw) else None,
            "y_trans": y_trans[idx] if idx < len(y_trans) else None,
        }
        for tid, d_res in dist_dict.items():
            de = _clean_opt_float(d_res["dist_eucl"][idx])
            dn = _clean_opt_float(d_res["dist_net"][idx])
            dd = _clean_opt_float(d_res["circuity_delta"][idx])
            tr = _clean_opt_float(d_res["circuity_ratio"][idx])
            props[f"dist_eucl_{tid}"] = None if de is None else round(de, 2)
            props[f"dist_net_{tid}"] = None if dn is None else round(dn, 2)
            tt_arr = d_res.get("travel_time_min")
            if tt_arr is not None and idx < len(tt_arr):
                ttv = _clean_opt_float(tt_arr[idx])
                props[f"travel_time_min_{tid}"] = None if ttv is None else round(ttv, 2)
            props[f"circuity_delta_{tid}"] = None if dd is None else round(dd, 2)
            props[f"circuity_ratio_{tid}"] = None if tr is None else round(tr, 4)

        pos_ols = ols_pos_map.get(idx)
        if pos_ols is not None and active_ols and pos_ols < len(active_ols.get("fitted", [])):
            props["ols_fitted"] = active_ols["fitted"][pos_ols]
            props["ols_resid"] = active_ols["resid"][pos_ols]
            props["ols_cooks_d"] = active_ols["cooks_d"][pos_ols]

        pos_sp = sp_pos_map.get(idx)
        if pos_sp is not None and spatial_res and spatial_res.get("ok"):
            ly = spatial_res.get("lisa_y", {})
            lr = spatial_res.get("lisa_resid", {})
            if pos_sp < len(ly.get("quadrants", [])):
                props["lisa_y_quad"] = ly["quadrants"][pos_sp]
                if pos_sp < len(ly.get("lisa_i", [])):
                    props["lisa_y_i"] = ly["lisa_i"][pos_sp]
                if pos_sp < len(ly.get("p_vals", [])):
                    props["lisa_y_p"] = ly["p_vals"][pos_sp]
                props["lisa_resid_quad"] = lr["quadrants"][pos_sp]
                if pos_sp < len(lr.get("lisa_i", [])):
                    props["lisa_resid_i"] = lr["lisa_i"][pos_sp]
                if pos_sp < len(lr.get("p_vals", [])):
                    props["lisa_resid_p"] = lr["p_vals"][pos_sp]

        pos_gwr = gwr_pos_map.get(idx)
        if pos_gwr is not None and gwr_res and gwr_res.get("ok"):
            if pos_gwr < len(gwr_res.get("local_r2", [])):
                props["gwr_local_r2"] = _clean_opt_float(gwr_res["local_r2"][pos_gwr])
                props["gwr_resid"] = _clean_opt_float(gwr_res["resid_native"][pos_gwr])
                kappas = gwr_res.get("local_kappas", [])
                if pos_gwr < len(kappas):
                    props["gwr_kappa"] = _clean_opt_float(kappas[pos_gwr])
                reg_flags = gwr_res.get("is_regularized", [])
                if pos_gwr < len(reg_flags):
                    props["gwr_reg_flag"] = int(bool(reg_flags[pos_gwr]))
                n_drp = gwr_res.get("n_local_dropped", [])
                if pos_gwr < len(n_drp):
                    props["gwr_n_dropped"] = int(n_drp[pos_gwr])
                se_mat = gwr_res.get("se_native", [])
                fdr_mat = gwr_res.get("fdr_sig_mask")
                for c_idx, safe_c in enumerate(gwr_safe_cols):
                    props[f"gwr_beta_{safe_c}"] = _clean_opt_float(gwr_res["betas_native"][pos_gwr][c_idx])
                    if pos_gwr < len(se_mat) and c_idx < len(se_mat[pos_gwr]):
                        props[f"gwr_se_{safe_c}"] = _clean_opt_float(se_mat[pos_gwr][c_idx])
                    props[f"gwr_t_{safe_c}"] = _clean_opt_float(gwr_res["t_vals"][pos_gwr][c_idx])
                    if fdr_mat and pos_gwr < len(fdr_mat) and c_idx < len(fdr_mat[pos_gwr]):
                        props[f"gwr_fdr_sig_{safe_c}"] = int(bool(fdr_mat[pos_gwr][c_idx]))

        features.append({
            "type": "Feature",
            "geometry": {"type": "Point", "coordinates": [float(lon_v), float(lat_v)]},
            "properties": props,
        })

    return {"type": "FeatureCollection", "features": features}


def generate_spatial_comparison_latex(spatial_res: Dict[str, Any], label: str = "tab:geospec_spatial") -> str:
    """Generate Overleaf-ready booktabs LaTeX table for Stage 4 OLS/SAR/SEM/SDM comparison with full tablenotes."""
    rows = spatial_res.get("model_comparison") or []
    if not rows:
        return "% No spatial model comparison available."
    safe_label = re.sub(r"[^A-Za-z0-9:._-]", "_", str(label))
    se_mode = str(spatial_res.get("se_mode", "qml")).upper()
    lines = [
        "% Generated by GeoSpec Stage 4 Spatial Econometrics",
        "% Requires: \\usepackage{booktabs,threeparttable,amsmath}",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\begin{threeparttable}",
        "\\caption{Spatial Econometric Model Comparison (OLS vs. SAR vs. SEM vs. SDM)}",
        f"\\label{{{safe_label}}}",
        "\\begin{tabular}{lccccccccc}",
        "\\toprule",
        "Model & $\\rho / \\lambda$ & SE & $p$-val & $R^2$/Ps.-$R^2$ & Log-Lik & AIC & BIC & Res. $I$ & Res. $p$ \\\\",
        "\\midrule",
    ]
    for r in rows:
        sp = f"{r['spatial_param']:.4f}" if isinstance(r.get("spatial_param"), (int, float)) else "---"
        se = f"{r['spatial_se']:.4f}" if isinstance(r.get("spatial_se"), (int, float)) else "---"
        pv = f"{r['spatial_p']:.4f}" if isinstance(r.get("spatial_p"), (int, float)) else "---"
        r2v = f"{r['r2_or_pseudo']:.4f}" if isinstance(r.get("r2_or_pseudo"), (int, float)) else "---"
        llf = f"{r['llf']:.2f}" if isinstance(r.get("llf"), (int, float)) else "---"
        aic = f"{r['aic']:.2f}" if isinstance(r.get("aic"), (int, float)) else "---"
        bic = f"{r['bic']:.2f}" if isinstance(r.get("bic"), (int, float)) else "---"
        mi = f"{r['resid_moran_i']:.4f}" if isinstance(r.get("resid_moran_i"), (int, float)) else "---"
        mp = f"{r['resid_moran_p']:.4f}" if isinstance(r.get("resid_moran_p"), (int, float)) else "---"
        lines.append(
            f"{_latex_escape(str(r.get('model', '')))} & {sp} & {se} & {pv} & {r2v} & {llf} & {aic} & {bic} & {mi} & {mp} \\\\"
        )

    ans_v = _latex_escape(str((spatial_res.get("anselin") or {}).get("verdict", "---")))
    elh_v = _latex_escape(str((spatial_res.get("elhorst") or {}).get("verdict", "---")))
    n_obs = spatial_res.get("n_obs", "---")
    pw = _latex_escape(str(spatial_res.get("primary_w_id", "primary")))
    lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
        "\\begin{tablenotes}[flushleft]",
        "\\footnotesize",
        f"\\item $N = {n_obs}$, primary weight matrix $W = \\text{{{pw}}}$, inference SE mode: {se_mode}.",
        f"\\item Anselin LM decision: {ans_v}. Elhorst common-factor verdict: {elh_v}.",
        "\\item Residual autocorrelation: OLS uses exact $M_X$ moments; SAR/SDM use Anselin--Kelejian (1997) moments; SEM reports post-filter residuals.",
        "\\end{tablenotes}",
        "\\end{threeparttable}",
        "\\end{table}",
    ])
    return "\n".join(lines)


def generate_spatial_params_latex(spatial_res: Dict[str, Any], label: str = "tab:geospec_spatial_params") -> str:
    """Generate Overleaf booktabs table comparing SAR, SEM, and SDM covariate estimates."""
    sar_p = {r["name"]: r for r in (spatial_res.get("sar_params") or [])}
    sem_p = {r["name"]: r for r in (spatial_res.get("sem_params") or [])}
    sdm_p = {r["name"]: r for r in (spatial_res.get("sdm_params") or [])}
    if not (sar_p or sem_p or sdm_p):
        return "% No spatial covariate parameters available."

    order: List[str] = []
    seen = set()
    for src in (spatial_res.get("sem_params") or [], spatial_res.get("sar_params") or [], spatial_res.get("sdm_params") or []):
        for r in src:
            if r["name"] not in seen:
                seen.add(r["name"])
                order.append(r["name"])

    safe_label = re.sub(r"[^A-Za-z0-9:._-]", "_", str(label))
    se_mode = str(spatial_res.get("se_mode", "qml")).upper()
    lines = [
        "% Generated by GeoSpec Stage 4 Spatial Regression Covariates",
        "% Requires: \\usepackage{booktabs,threeparttable,amsmath}",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\begin{threeparttable}",
        f"\\caption{{Spatial ML Covariate Estimates (SAR, SEM, SDM; {se_mode} SEs)}}",
        f"\\label{{{safe_label}}}",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "Variable & SEM & SAR & SDM \\\\",
        "\\midrule",
    ]
    for pname in order:
        c_cells, s_cells = [], []
        for pmap in (sem_p, sar_p, sdm_p):
            if pname in pmap:
                r = pmap[pname]
                c_cells.append(f"{r['est']:.4f}{_sig_stars(r.get('p'))}")
                s_cells.append(f"({r['se']:.4f})")
            else:
                c_cells.append("---")
                s_cells.append("")
        lines.append(f"{_latex_escape(pname)} & " + " & ".join(c_cells) + " \\\\")
        if any(s_cells):
            lines.append(" & " + " & ".join(s_cells) + " \\\\")
    lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
        "\\begin{tablenotes}[flushleft]",
        "\\footnotesize",
        f"\\item $N = {spatial_res.get('n_obs', '---')}$, primary $W = \\text{{{_latex_escape(str(spatial_res.get('primary_w_id', 'W')))}}}$, SE mode: {se_mode}. $^{{***}}p<0.01, ^{{**}}p<0.05, ^{{*}}p<0.10$.",
        "\\end{tablenotes}",
        "\\end{threeparttable}",
        "\\end{table}",
    ])
    return "\n".join(lines)


def generate_robustness_matrix_latex(rob_res: Dict[str, Any], label: str = "tab:geospec_robustness") -> str:
    """Generate functional-form & SE robustness matrix Overleaf booktabs table."""
    rows = rob_res.get("rows") or []
