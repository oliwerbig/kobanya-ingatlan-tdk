"""
Publication-Grade Exporters (Overleaf Booktabs LaTeX, QGIS GeoJSON, CSV/JSON/ZIP)
=================================================================================
Pure Python stdlib exporter generating:
- Multi-model comparison Overleaf `booktabs` LaTeX tables with automatic Kennedy/HP
  and Guard #2/#4 footnotes
- RFC-7946 `EPSG:4326` QGIS GeoJSON with computed distances, circuity, residuals,
  LISA quadrants, and native GWR local beta/t estimates
- CSV, Markdown, JSON tables, portable `experiment_recipe.json`, and ZIP archive bytes
"""

from __future__ import annotations

import csv
import io
import json
import zipfile
from typing import Any, Dict, List, Optional


def _latex_escape(text: str) -> str:
    """Escape LaTeX special characters cleanly."""
    s = str(text)
    for old, new in [
        ("\\", "\\textbackslash{}"),
        ("&", "\\&"),
        ("%", "\\%"),
        ("$", "\\$"),
        ("#", "\\#"),
        ("_", "\\_"),
        ("{", "\\{"),
        ("}", "\\}"),
        ("~", "\\textasciitilde{}"),
        ("^", "\\textasciicircum{}"),
    ]:
        s = s.replace(old, new)
    return s


def _sig_stars(p: Optional[float]) -> str:
    if p is None:
        return ""
    if p < 0.01:
        return "$^{***}$"
    if p < 0.05:
        return "$^{**}$"
    if p < 0.10:
        return "$^{*}$"
    return ""


def generate_multi_model_latex(
    ols_models: List[Dict[str, Any]],
    caption: str = "Hedonic & Spatial Regression Comparison",
    label: str = "tab:geospec_models",
    show_pct_for_dummies: bool = False,
) -> str:
    """
    Generate an Overleaf-ready `booktabs` multi-model LaTeX table comparing composed specs.
    Includes standard errors in parentheses, significance stars, diagnostic footer, and Guard footnotes.
    """
    if not ols_models:
        return "% No fitted OLS models available."

    # Collect ordered union of variable names across models
    var_order: List[str] = []
    seen = set()
    for m in ols_models:
        for row in m.get("params", []):
            name = row["name"]
            if name not in seen:
                seen.add(name)
                var_order.append(name)

    n_cols = len(ols_models)
    col_spec = "l" + "c" * n_cols
    headers = " & ".join(_latex_escape(m.get("model_name", m["model_id"])) for m in ols_models)

    lines = [
        "% Generated by GeoSpec (Pure NumPy+SciPy Spatial Econometric Workbench)",
        "% Requires: \\usepackage{booktabs,threeparttable}",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\begin{threeparttable}",
        f"\\caption{{{_latex_escape(caption)}}}",
        f"\\label{{{label}}}",
        f"\\begin{{tabular}}{{{col_spec}}}",
        "\\toprule",
        f"Variable & {headers} \\\\",
        "\\midrule",
    ]

    model_param_maps = [{r["name"]: r for r in m.get("params", [])} for m in ols_models]

    for vname in var_order:
        coef_cells = []
        se_cells = []
        for pmap in model_param_maps:
            if vname in pmap:
                r = pmap[vname]
                stars = _sig_stars(r.get("p"))
                if show_pct_for_dummies and r.get("kennedy_pct") is not None:
                    coef_cells.append(f"{r['beta']:.4f}{stars} [{r['kennedy_pct']:+.1f}\\%]")
                else:
                    coef_cells.append(f"{r['beta']:.4f}{stars}")
                se_cells.append(f"({r['se']:.4f})")
            else:
                coef_cells.append("---")
                se_cells.append("")
        lines.append(f"{_latex_escape(vname)} & " + " & ".join(coef_cells) + " \\\\")
        if any(se_cells):
            lines.append(" & " + " & ".join(se_cells) + " \\\\")

    lines.append("\\midrule")

    def _footer_row(title: str, key: str, fmt: str = "{:.4f}") -> str:
        vals = []
        for m in ols_models:
            v = m.get(key)
            if v is None:
                diag = m.get("diagnostics", {})
                v = diag.get(key)
            vals.append(fmt.format(v) if isinstance(v, (int, float)) else (str(v) if v is not None else "---"))
        return f"{title} & " + " & ".join(vals) + " \\\\"

    lines.append(_footer_row("$N$", "n_obs", "{:d}"))
    lines.append(_footer_row("$R^2$", "r2", "{:.4f}"))
    lines.append(_footer_row("Adj. $R^2$", "adj_r2", "{:.4f}"))
    lines.append(_footer_row("AIC", "aic", "{:.2f}"))
    lines.append(_footer_row("Max VIF", "max_vif", "{:.2f}"))
    lines.append(_footer_row("RESET $p$-value", "reset_p", "{:.4f}"))
    lines.append(_footer_row("SE Type", "cov_type_used", "{}"))
    lines.extend(["\\bottomrule", "\\end{tabular}"])

    # Collect Guard footnotes
    notes: List[str] = ["Standard errors in parentheses. $^{***}p<0.01$, $^{**}p<0.05$, $^{*}p<0.10$."]
    if any(m.get("is_log_scale") for m in ols_models):
        notes.append("Semi-log dummy impacts computed via Halvorsen--Palmquist and Kennedy (1981) variance-corrected transformations.")
    for m in ols_models:
        for fn in m.get("footnotes", []):
            notes.append(f"[{m['model_id']}] {_latex_escape(fn)}")

    lines.append("\\begin{tablenotes}[flushleft]")
    lines.append("\\small")
    for note in notes:
        lines.append(f"\\item {note}")
    lines.append("\\end{tablenotes}")
    lines.append("\\end{threeparttable}")
    lines.append("\\end{table}")
    return "\n".join(lines)


def dict_rows_to_csv(rows: List[Dict[str, Any]]) -> str:
    """Serialize list of uniform dicts to UTF-8 CSV string."""
    if not rows:
        return ""
    buf = io.StringIO()
    headers = list(rows[0].keys())
    writer = csv.DictWriter(buf, fieldnames=headers)
    writer.writeheader()
    for r in rows:
        writer.writerow(r)
    return buf.getvalue()


def dict_rows_to_markdown(rows: List[Dict[str, Any]]) -> str:
    """Serialize list of dicts to GitHub-Flavored Markdown table."""
    if not rows:
        return ""
    headers = list(rows[0].keys())
    lines = [
        "| " + " | ".join(str(h) for h in headers) + " |",
        "| " + " | ".join(":---" for _ in headers) + " |",
    ]
    for r in rows:
        lines.append("| " + " | ".join("" if r.get(h) is None else str(r.get(h)) for h in headers) + " |")
    return "\n".join(lines)


def build_qgis_geojson(
    lat_arr: List[Optional[float]],
    lon_arr: List[Optional[float]],
    row_ids: List[Any],
    y_raw: List[Optional[float]],
    y_trans: List[Optional[float]],
    dist_dict: Dict[str, Dict[str, Any]],
    active_ols: Optional[Dict[str, Any]] = None,
    spatial_res: Optional[Dict[str, Any]] = None,
    gwr_res: Optional[Dict[str, Any]] = None,
    analytic_indices: Optional[List[int]] = None,
) -> Dict[str, Any]:
    """
    Build RFC-7946 EPSG:4326 GeoJSON FeatureCollection enriched with computed OSM distances,
    circuity, OLS residuals, LISA clusters, and native GWR local parameters.
    """
    analytic_pos_map: Dict[int, int] = {}
    if analytic_indices is not None:
        analytic_pos_map = {int(orig_i): pos for pos, orig_i in enumerate(analytic_indices)}

    features = []
    for idx in range(len(lat_arr)):
        lat_v = lat_arr[idx]
        lon_v = lon_arr[idx]
        if lat_v is None or lon_v is None:
            continue
        props: Dict[str, Any] = {
            "row_id": row_ids[idx] if idx < len(row_ids) else idx,
            "y_raw": y_raw[idx] if idx < len(y_raw) else None,
            "y_trans": y_trans[idx] if idx < len(y_trans) else None,
        }
        for tid, d_res in dist_dict.items():
            de = d_res["dist_eucl"][idx]
            dn = d_res["dist_net"][idx]
            dd = d_res["circuity_delta"][idx]
            tr = d_res["circuity_ratio"][idx]
            props[f"dist_eucl_{tid}"] = None if (de is None or de != de) else round(float(de), 2)
            props[f"dist_net_{tid}"] = None if (dn is None or dn != dn) else round(float(dn), 2)
            props[f"circuity_delta_{tid}"] = None if (dd is None or dd != dd) else round(float(dd), 2)
            props[f"circuity_ratio_{tid}"] = None if (tr is None or tr != tr) else round(float(tr), 4)

        pos = analytic_pos_map.get(idx)
        if pos is not None:
            if active_ols:
                props["ols_fitted"] = active_ols["fitted"][pos]
                props["ols_resid"] = active_ols["resid"][pos]
                props["ols_cooks_d"] = active_ols["cooks_d"][pos]
            if spatial_res and spatial_res.get("ok"):
                props["lisa_y_quad"] = spatial_res["lisa_y"]["quadrants"][pos]
                props["lisa_resid_quad"] = spatial_res["lisa_resid"]["quadrants"][pos]
            if gwr_res and gwr_res.get("ok"):
                props["gwr_local_r2"] = gwr_res["local_r2"][pos]
                props["gwr_resid"] = gwr_res["resid_native"][pos]
                for c_idx, cname in enumerate(gwr_res["col_names"]):
                    safe_c = "".join(ch if ch.isalnum() else "_" for ch in cname).strip("_")
                    props[f"gwr_beta_{safe_c}"] = gwr_res["betas_native"][pos][c_idx]
                    props[f"gwr_t_{safe_c}"] = gwr_res["t_vals"][pos][c_idx]

        features.append({
            "type": "Feature",
            "geometry": {"type": "Point", "coordinates": [float(lon_v), float(lat_v)]},
            "properties": props,
        })

    return {"type": "FeatureCollection", "features": features}


def build_zip_bundle(
    tables: Dict[str, List[Dict[str, Any]]],
    latex_tables: Dict[str, str],
    geojson_data: Dict[str, Any],
    recipe: Dict[str, Any],
    manifest: Dict[str, Any],
) -> bytes:
    """Build complete reproducible scientific archive ZIP in memory."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        for name, rows in tables.items():
            if not rows:
                continue
            zf.writestr(f"csv/{name}.csv", dict_rows_to_csv(rows).encode("utf-8-sig"))
            zf.writestr(f"markdown/{name}.md", dict_rows_to_markdown(rows).encode("utf-8"))
            zf.writestr(f"json/{name}.json", json.dumps(rows, indent=2, ensure_ascii=False).encode("utf-8"))

        for name, tex in latex_tables.items():
            zf.writestr(f"latex/{name}.tex", tex.encode("utf-8"))

        zf.writestr("spatial/enriched_observations.geojson", json.dumps(geojson_data, ensure_ascii=False).encode("utf-8"))
        zf.writestr("experiment_recipe.json", json.dumps(recipe, indent=2, ensure_ascii=False).encode("utf-8"))
        zf.writestr("reproducibility_manifest.json", json.dumps(manifest, indent=2, ensure_ascii=False).encode("utf-8"))

    return buf.getvalue()
