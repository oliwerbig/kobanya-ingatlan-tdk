    lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
        "\\begin{tablenotes}[flushleft]",
        "\\footnotesize",
        *[f"\\item {nt}" for nt in notes_gwr],
        "\\end{tablenotes}",
        "\\end{threeparttable}",
        "\\end{table}",
    ])
    return "\n".join(lines)


